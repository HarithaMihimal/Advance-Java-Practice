class Hello{
    public static void main(String[] args) {
        //literals
        int num  = 1_000_000_000;
        System.out.println(num);    

        float f = 3.14f;
        System.out.println(f);

        double d  = 12;
        System.out.println(d);

        double d2 = 12e3;
        System.out.println(d2);

        boolean b  = true;
        System.out.println(b);
        
        char c = 'A';
        System.out.println(c);
        c++;
        System.out.println(c);
    }
}